import {readFile,stat} from 'node:fs/promises';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {resolve} from 'node:path';
import {validateCampaign,writeJson} from './core.mjs';
const exec = promisify(execFile);
const event = JSON.parse(await readFile(process.env.GITHUB_EVENT_PATH,'utf8'));
const repo = process.env.GITHUB_REPOSITORY;
const {stdout} = await exec('gh',['api',`repos/${repo}/collaborators/${encodeURIComponent(event.issue.user.login)}/permission`]);
if(!['admin','write','maintain'].includes(JSON.parse(stdout).permission)) throw new Error('Only repository maintainers can create campaigns through issues');
const match=event.issue.body?.match(/```(?:json)?\s*([\s\S]*?)```/);
if(!match) throw new Error('Paste exported JSON in the Campaign JSON field');
const c=validateCampaign(JSON.parse(match[1]));
const config=JSON.parse(await readFile('config/chapter.json','utf8'));
if(c.year!==config.activeYear || Date.parse(c.start)<=Date.now()) throw new Error('Choose a future event in the active year');
const file=resolve('data/campaigns',c.year,`${c.id}.json`);
if(await stat(file).catch(()=>null)) throw new Error('A campaign with this ID already exists');
delete c.demo; delete c.archived; delete c.cancelled;
c.status={feed:'pending',story:'pending',groupme:'pending'};
c.results={feed:{},story:{},groupme:{},insights:[]}; c.log=[];c.revision=1;
await writeJson(file,c);
console.log(`Validated campaign ${c.id}`);
